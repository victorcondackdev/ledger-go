package ledger

import (
	"fmt"
	"time"

	"github.com/victorcondackdev/ledger-go/money"
)

// TxID identifies a transaction.
type TxID string

// Kind says what a transaction does and how its postings are interpreted.
type Kind uint8

// Transaction kinds.
const (
	// KindStandard postings move posted balances immediately.
	KindStandard Kind = iota + 1
	// KindPending postings are holds: they move pending balances and
	// reduce available balances until resolved.
	KindPending
	// KindPostPending settles (part of) a pending transfer. Its postings
	// are the amounts posted; the whole hold is released.
	KindPostPending
	// KindVoidPending cancels a pending transfer. Its postings are the
	// released holds.
	KindVoidPending
	// KindExpirePending is a void performed by [Ledger.ExpirePending]
	// after the pending transfer's timeout.
	KindExpirePending
	// KindReversal compensates a standard or posted-pending transaction
	// with mirrored postings.
	KindReversal
)

// String returns the kind name, e.g. "post_pending".
func (k Kind) String() string {
	switch k {
	case KindStandard:
		return "standard"
	case KindPending:
		return "pending"
	case KindPostPending:
		return "post_pending"
	case KindVoidPending:
		return "void_pending"
	case KindExpirePending:
		return "expire_pending"
	case KindReversal:
		return "reversal"
	}
	return fmt.Sprintf("Kind(%d)", uint8(k))
}

// Posting is one leg of a transaction: an amount debited or credited to an
// account. Amounts are always positive; the direction carries the sign.
type Posting struct {
	Account   AccountID
	Direction Direction
	Amount    money.Amount
}

// Transaction is an immutable, sealed ledger record.
type Transaction struct {
	// ID is unique, generated by the ledger.
	ID TxID
	// Seq is the 1-based position in the audit chain. It is gap-free and
	// gives every consumer (statements, outbox, replicas) a total order.
	Seq uint64
	// Kind says how Postings are interpreted.
	Kind Kind
	// IdempotencyKey is the caller's key, or "" for none.
	IdempotencyKey string
	// Ref links to the related transaction: the pending transfer for
	// post/void/expire, the original for a reversal.
	Ref TxID
	// Timestamp is assigned by the ledger clock and never decreases along
	// the chain.
	Timestamp time.Time
	// ExpiresAt is the timeout of a KindPending transaction (zero: never).
	ExpiresAt time.Time
	// Description is free text for statements.
	Description string
	// Metadata is free key/value data (end-to-end IDs, MED case numbers…).
	Metadata map[string]string
	// Postings are the legs, in request order.
	Postings []Posting
	// RequestHash fingerprints the request, for idempotent replays.
	RequestHash [32]byte
	// PrevHash is the Hash of the transaction with Seq-1 (zero for the
	// first).
	PrevHash [32]byte
	// Hash is SHA-256(PrevHash || canonical encoding); see
	// [Ledger.VerifyChain].
	Hash [32]byte
}

// Clone returns a deep copy, so that callers and stores never share the
// Postings slice or Metadata map.
func (t Transaction) Clone() Transaction {
	if t.Postings != nil {
		t.Postings = append([]Posting(nil), t.Postings...)
	}
	if t.Metadata != nil {
		m := make(map[string]string, len(t.Metadata))
		for k, v := range t.Metadata {
			m[k] = v
		}
		t.Metadata = m
	}
	return t
}

// Phase says which balance counters an [Entry] moved.
type Phase uint8

// Entry phases.
const (
	// PhasePosted entries move posted counters.
	PhasePosted Phase = iota + 1
	// PhaseHeld entries add to pending counters.
	PhaseHeld
	// PhaseReleased entries remove a hold from pending counters.
	PhaseReleased
)

// String returns "posted", "held" or "released".
func (p Phase) String() string {
	switch p {
	case PhasePosted:
		return "posted"
	case PhaseHeld:
		return "held"
	case PhaseReleased:
		return "released"
	}
	return fmt.Sprintf("Phase(%d)", uint8(p))
}

// Entry is the effect of one transaction leg on one account, with the
// account's counters right after it. Entries are what statements and
// point-in-time balances are built from; in SQL they are the
// ledger_entries table, with Balances as the balance_after columns.
type Entry struct {
	// AccountSeq is the 1-based position among the account's entries; a
	// transaction with two legs on the same account produces two entries
	// with the same Seq but distinct AccountSeq. Cursors use it.
	AccountSeq uint64
	// Seq is the transaction's chain sequence number.
	Seq       uint64
	TxID      TxID
	Kind      Kind
	Time      time.Time
	Account   AccountID
	Direction Direction
	Phase     Phase
	// Amount is positive, in minor units of the account's currency.
	Amount int64
	// After are the account's counters after this entry.
	After Balances
}

// PendingStatus is the state of a two-phase transfer.
type PendingStatus uint8

// Pending transfer states. Open is the only non-terminal one.
const (
	PendingOpen PendingStatus = iota + 1
	PendingPosted
	PendingVoided
	PendingExpired
)

// String returns the status name.
func (s PendingStatus) String() string {
	switch s {
	case PendingOpen:
		return "open"
	case PendingPosted:
		return "posted"
	case PendingVoided:
		return "voided"
	case PendingExpired:
		return "expired"
	}
	return fmt.Sprintf("PendingStatus(%d)", uint8(s))
}

// PendingTransfer is the state machine record of a KindPending
// transaction. The transaction itself is immutable; this record moves from
// Open to exactly one terminal state.
type PendingTransfer struct {
	ID        TxID
	Status    PendingStatus
	ExpiresAt time.Time // zero: never
	Postings  []Posting
	// ResolvedBy is the post/void/expire transaction, once resolved.
	ResolvedBy TxID
}

// ChainHead is the tip of the audit chain.
type ChainHead struct {
	Seq  uint64
	Hash [32]byte
	Time time.Time
}
